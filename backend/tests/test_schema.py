def _user(db) -> uuid.UUID:
    return db.execute(
        "INSERT INTO users (email, display_name, password_hash) VALUES (%s, 'u', 'x') RETURNING id",
        (f"{uuid.uuid4()}@example.test",),
    ).fetchone()[0]


def _workspace(db) -> uuid.UUID:
    return db.execute("INSERT INTO workspaces (name) VALUES ('w') RETURNING id").fetchone()[0]


def _member(db, workspace_id, user_id, role="member") -> None:
    db.execute(
        "INSERT INTO memberships (workspace_id, user_id, role) VALUES (%s, %s, %s)",
        (workspace_id, user_id, role),
    )


def _document_with_version(db, workspace_id, author_id) -> tuple[uuid.UUID, uuid.UUID]:
    doc = db.execute(
        "INSERT INTO documents (workspace_id, author_id) VALUES (%s, %s) RETURNING id",
        (workspace_id, author_id),
    ).fetchone()[0]
    version = db.execute(
        "INSERT INTO document_versions (workspace_id, document_id, title, body, created_by) "
        "VALUES (%s, %s, 't', 'b', %s) RETURNING id",
        (workspace_id, doc, author_id),
    ).fetchone()[0]
    return doc, version


def test_group_membership_cannot_cross_workspaces(db):
    user = _user(db)
    ws_a, ws_b = _workspace(db), _workspace(db)
    _member(db, ws_a, user)
    group_b = db.execute(
        "INSERT INTO groups (workspace_id, name) VALUES (%s, 'g') RETURNING id", (ws_b,)
    ).fetchone()[0]
    with pytest.raises(psycopg.errors.ForeignKeyViolation):
        db.execute(
            "INSERT INTO group_members (workspace_id, group_id, user_id) VALUES (%s, %s, %s)",
            (ws_a, group_b, user),
        )


