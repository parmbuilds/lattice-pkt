import uuid

import psycopg
import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from tests.conftest import BACKEND, plain_dsn


@pytest.fixture
def db(pg):
    """A runtime-role (lattice_app) connection; each test rolls back."""
    with psycopg.connect(plain_dsn(pg["app"])) as conn:
        yield conn
        conn.rollback()


def _user(db) -> uuid.UUID:
    return db.execute(
        "INSERT INTO users (email, display_name, password_hash) VALUES (%s, 'u', 'x') RETURNING id",
        (f"{uuid.uuid4()}@example.test",),
    ).fetchone()[0]


def _workspace(db) -> uuid.UUID:
    return db.execute("INSERT INTO workspaces (name) VALUES ('w') RETURNING id").fetchone()[0]


def _member(db, workspace_id, user_id, role="member") -> None:
    db.execute(
        "INSERT INTO memberships (workspace_id, user_id, role) VALUES (%s, %s, %s)",
        (workspace_id, user_id, role),
    )


def _document_with_version(db, workspace_id, author_id) -> tuple[uuid.UUID, uuid.UUID]:
    doc = db.execute(
        "INSERT INTO documents (workspace_id, author_id) VALUES (%s, %s) RETURNING id",
        (workspace_id, author_id),
    ).fetchone()[0]
    version = db.execute(
        "INSERT INTO document_versions (workspace_id, document_id, title, body, created_by) "
        "VALUES (%s, %s, 't', 'b', %s) RETURNING id",
        (workspace_id, doc, author_id),
    ).fetchone()[0]
    return doc, version


def test_group_membership_cannot_cross_workspaces(db):
    user = _user(db)
    ws_a, ws_b = _workspace(db), _workspace(db)
    _member(db, ws_a, user)
    group_b = db.execute(
        "INSERT INTO groups (workspace_id, name) VALUES (%s, 'g') RETURNING id", (ws_b,)
    ).fetchone()[0]
    with pytest.raises(psycopg.errors.ForeignKeyViolation):
        db.execute(
            "INSERT INTO group_members (workspace_id, group_id, user_id) VALUES (%s, %s, %s)",
            (ws_a, group_b, user),
        )


def test_a_workspace_has_at_most_one_owner(db):
    ws = _workspace(db)
    _member(db, ws, _user(db), "owner")
    with pytest.raises(psycopg.errors.UniqueViolation):
        _member(db, ws, _user(db), "owner")


def test_the_same_user_cannot_join_a_workspace_twice(db):
    ws, user = _workspace(db), _user(db)
    _member(db, ws, user)
    with pytest.raises(psycopg.errors.UniqueViolation):
        _member(db, ws, user, "admin")


def test_runtime_role_cannot_update_delete_or_truncate_audit_events(db):
    ws = _workspace(db)
    db.execute(
        "INSERT INTO audit_events (workspace_id, channel, action, outcome) "
        "VALUES (%s, 'system', 'test', 'allow')",
        (ws,),
    )
    for statement in (
        "UPDATE audit_events SET action = 'x'",
        "DELETE FROM audit_events",
        "TRUNCATE audit_events",
    ):
        with pytest.raises(psycopg.errors.InsufficientPrivilege), db.transaction():
            db.execute(statement)


def test_runtime_role_cannot_update_or_delete_document_versions(db):
    ws, user = _workspace(db), _user(db)
    _member(db, ws, user)
    _document_with_version(db, ws, user)
    for statement in ("UPDATE document_versions SET body = 'x'", "DELETE FROM document_versions"):
        with pytest.raises(psycopg.errors.InsufficientPrivilege), db.transaction():
            db.execute(statement)


def test_owner_role_is_also_blocked_by_the_immutability_triggers(pg):
    # Defence in depth: even the table owner cannot rewrite history without dropping triggers.
    with psycopg.connect(plain_dsn(pg["owner"])) as owner:
        ws = _workspace(owner)
        user = _user(owner)
        _member(owner, ws, user)
        _document_with_version(owner, ws, user)
        with pytest.raises(psycopg.errors.RaiseException), owner.transaction():
            owner.execute("UPDATE document_versions SET body = 'x'")
        owner.rollback()


def test_serving_pointer_cannot_reference_another_documents_version(db):
    ws, user = _workspace(db), _user(db)
    _member(db, ws, user)
    doc_a, _ = _document_with_version(db, ws, user)
    _, version_b = _document_with_version(db, ws, user)
    with pytest.raises(psycopg.errors.ForeignKeyViolation):
        db.execute("UPDATE documents SET serving_version_id = %s WHERE id = %s", (version_b, doc_a))


def test_a_grant_names_exactly_one_subject(db):
    ws, user = _workspace(db), _user(db)
    _member(db, ws, user)
    doc, _ = _document_with_version(db, ws, user)
    group = db.execute(
        "INSERT INTO groups (workspace_id, name) VALUES (%s, 'g') RETURNING id", (ws,)
    ).fetchone()[0]
    for group_id, user_id in ((group, user), (None, None)):
        with pytest.raises(psycopg.errors.CheckViolation), db.transaction():
            db.execute(
                "INSERT INTO document_grants (workspace_id, document_id, group_id, user_id) "
                "VALUES (%s, %s, %s, %s)",
                (ws, doc, group_id, user_id),
            )


def test_runtime_role_owns_nothing_and_has_no_destructive_audit_privileges(pg):
    with psycopg.connect(plain_dsn(pg["superuser"])) as su:
        owned = su.execute(
            "SELECT count(*) FROM pg_class c JOIN pg_roles r ON r.oid = c.relowner "
            "WHERE r.rolname = 'lattice_app'"
        ).fetchone()[0]
        is_member = su.execute(
            "SELECT pg_has_role('lattice_app', 'lattice_owner', 'MEMBER')"
        ).fetchone()[0]
        privileges = {
            privilege: su.execute(
                "SELECT has_table_privilege('lattice_app', 'audit_events', %s)", (privilege,)
            ).fetchone()[0]
            for privilege in ("UPDATE", "DELETE", "TRUNCATE", "TRIGGER", "INSERT", "SELECT")
        }
    assert owned == 0
    assert is_member is False
    assert privileges == {
        "UPDATE": False,
        "DELETE": False,
        "TRUNCATE": False,
        "TRIGGER": False,
        "INSERT": True,
        "SELECT": True,
    }


def test_models_match_the_migrated_schema(pg):
    config = Config(str(BACKEND / "alembic.ini"))
    config.set_main_option("sqlalchemy.url", pg["owner"])
    try:
        command.check(config)
    except AutogenerateDiffsDetected as diffs:  # pragma: no cover - failure path
        pytest.fail(str(diffs))
