def test_migration_refuses_a_database_without_the_vector_extension(pg):
    # KTD2: the superuser installs pgvector; the migration only checks and explains.
    super_dsn = plain_dsn(pg["superuser"])
    with psycopg.connect(super_dsn, autocommit=True) as su:
        su.execute("CREATE DATABASE no_vector OWNER lattice_owner")
    try:
        config = Config(str(BACKEND / "alembic.ini"))
        config.set_main_option("sqlalchemy.url", pg["owner"].rsplit("/", 1)[0] + "/no_vector")
        with pytest.raises(RuntimeError, match="CREATE EXTENSION vector"):
            command.upgrade(config, "head")
    finally:
        with psycopg.connect(super_dsn, autocommit=True) as su:
            su.execute("DROP DATABASE no_vector")


def test_a_database_already_at_0004_upgrades_to_the_models(pg):
    """0004 shipped to databases before turn_sources existed (KTD4); what came after lives in
    later migrations, so a database that stopped at 0004 reaches the same schema as a fresh one."""
    name = f"lattice_upgrade_{uuid.uuid4().hex[:8]}"

    def on(url: str) -> str:
        return url.rsplit("/", 1)[0] + f"/{name}"

    with psycopg.connect(plain_dsn(pg["superuser"]), autocommit=True) as su:
        su.execute(f"CREATE DATABASE {name} OWNER lattice_owner")
    try:
        with psycopg.connect(on(plain_dsn(pg["superuser"]))) as su:
            # As db/init/01-roles.sql prepares a new database.
            su.execute("CREATE EXTENSION IF NOT EXISTS vector")
            su.execute("ALTER SCHEMA public OWNER TO lattice_owner")
            su.execute("REVOKE ALL ON SCHEMA public FROM PUBLIC")
            su.execute("GRANT USAGE ON SCHEMA public TO lattice_app")
        config = Config(str(BACKEND / "alembic.ini"))
        config.set_main_option("sqlalchemy.url", on(pg["owner"]))
        command.upgrade(config, "0004")
        command.upgrade(config, "head")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as diffs:  # pragma: no cover - failure path
            pytest.fail(str(diffs))
    finally:
        with psycopg.connect(plain_dsn(pg["superuser"]), autocommit=True) as su:
            su.execute(f"DROP DATABASE IF EXISTS {name} WITH (FORCE)")


